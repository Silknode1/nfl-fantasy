import { chromium } from 'playwright'
const url = 'file://' + process.cwd() + '/dist-artifact/index.html#trades'
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
const errs = []
page.on('console', m => { if (m.type() === 'error') errs.push(m.text()) })
page.on('pageerror', e => errs.push(String(e)))
await page.goto(url)
await page.waitForSelector('.trade-item', { timeout: 20000 })
await page.selectOption('.builder select', { label: 'CutchToldUs' })
const tick = async (fieldset, name) => page.locator(`.builder fieldset:nth-of-type(${fieldset}) label.pick`, { hasText: name }).first().locator('input').check()
await tick(1, 'Tyler Warren'); await tick(1, 'DeVonta Smith')
await tick(2, 'Matthew Golden'); await tick(2, 'Ashton Jeanty')
await page.click('button.primary')
await page.waitForSelector('.decline-flag', { timeout: 10000 })
console.log('flag:', (await page.locator('.decline-flag').innerText()).slice(0, 160))
console.log('counters:', await page.locator('.counters .trade-item').count())
console.log((await page.locator('.counters').innerText()).replace(/\n+/g, ' | ').slice(0, 400))
await page.locator('.counters .trade-item').first().click()
await page.waitForTimeout(500)
console.log('after click, flag present:', await page.locator('.decline-flag').count(), '| grade:', (await page.locator('.preview .grade-col').innerText()).replace(/\n/g, ' '))
await page.screenshot({ path: 'shot-counters.png', fullPage: true })
console.log('errors:', errs.slice(0, 5))
await browser.close()
